// Gera/atualiza crypto.encryptionKeyBase64 em um arquivo de environment
const fs = require('fs');
const crypto = require('crypto');

function updateCryptoKey(envPath, envFile) {
  if (!fs.existsSync(envPath)) {
    return;
  }

  let envContent = fs.readFileSync(envPath, 'utf8');

  // Apenas atua se autogeneredKeyBuildDeploy estiver true no bloco crypto
  if (!/crypto\s*:\s*\{[\s\S]*autogeneredKeyBuildDeploy:\s*true/.test(envContent)) {
    return;
  }

  const keyBytes = crypto.randomBytes(32);
  const base64Key = keyBytes.toString('base64');
  const encryptionKeyRegex = /(encryptionKeyBase64:\s*)['"][^'"]*['"]/;

  if (encryptionKeyRegex.test(envContent)) {
    envContent = envContent.replace(encryptionKeyRegex, `$1'${base64Key}'`);
    fs.writeFileSync(envPath, envContent, 'utf8');
    console.log(`${envFile} crypto.encryptionKeyBase64 autogenerated for build`);
  } else {
    console.warn(`encryptionKeyBase64 property not found in ${envFile} (crypto block)`);
  }
}

module.exports = { updateCryptoKey };
